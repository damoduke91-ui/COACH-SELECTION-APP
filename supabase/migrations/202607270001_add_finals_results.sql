CREATE TABLE IF NOT EXISTS public.finals_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  environment text NOT NULL CHECK (environment IN ('production', 'preview')),
  season_year integer NOT NULL DEFAULT EXTRACT(YEAR FROM CURRENT_DATE)::integer,
  match_code text NOT NULL CHECK (match_code IN ('QF', 'EF', 'SF1', 'SF2', 'PF', 'GF')),
  coach_1_score numeric,
  coach_2_score numeric,
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT finals_results_environment_season_match_key UNIQUE (environment, season_year, match_code),
  CONSTRAINT finals_results_scores_together CHECK (
    (coach_1_score IS NULL AND coach_2_score IS NULL)
    OR (coach_1_score IS NOT NULL AND coach_2_score IS NOT NULL)
  ),
  CONSTRAINT finals_results_no_draws CHECK (
    coach_1_score IS NULL OR coach_2_score IS NULL OR coach_1_score <> coach_2_score
  )
);

ALTER TABLE public.finals_results ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Authenticated users can read finals results"
ON public.finals_results FOR SELECT TO authenticated USING (true);

CREATE POLICY "Admins can insert finals results"
ON public.finals_results FOR INSERT TO authenticated
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid()
      AND profiles.role = 'admin'
      AND profiles.environment = finals_results.environment
  )
);

CREATE POLICY "Admins can update finals results"
ON public.finals_results FOR UPDATE TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid()
      AND profiles.role = 'admin'
      AND profiles.environment = finals_results.environment
  )
)
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid()
      AND profiles.role = 'admin'
      AND profiles.environment = finals_results.environment
  )
);

CREATE INDEX IF NOT EXISTS finals_results_environment_season_idx
ON public.finals_results (environment, season_year);
