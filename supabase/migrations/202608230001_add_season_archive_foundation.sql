-- Batch 2: durable season identity, immutable closeout records, and write locks.
-- This migration is additive and backfills all existing competition data to 2026.

CREATE TABLE IF NOT EXISTS public.competition_seasons (
  environment text NOT NULL CHECK (environment IN ('production', 'preview')),
  season_year integer NOT NULL CHECK (season_year BETWEEN 2000 AND 2100),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'active', 'completed', 'archived')),
  started_at timestamptz,
  completed_at timestamptz,
  archived_at timestamptz,
  locked_at timestamptz,
  premier_coach_id integer,
  premier_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (environment, season_year),
  CHECK (status NOT IN ('completed', 'archived') OR locked_at IS NOT NULL),
  CHECK (status <> 'archived' OR archived_at IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS competition_seasons_one_active_per_environment
ON public.competition_seasons (environment)
WHERE status = 'active';

CREATE TABLE IF NOT EXISTS public.season_archives (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  environment text NOT NULL CHECK (environment IN ('production', 'preview')),
  season_year integer NOT NULL CHECK (season_year BETWEEN 2000 AND 2100),
  archive_version integer NOT NULL DEFAULT 1 CHECK (archive_version > 0),
  payload jsonb NOT NULL,
  source_row_counts jsonb NOT NULL,
  checksum text NOT NULL CHECK (length(btrim(checksum)) >= 32),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (environment, season_year, archive_version),
  FOREIGN KEY (environment, season_year)
    REFERENCES public.competition_seasons (environment, season_year)
);

ALTER TABLE public.competition_seasons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.season_archives ENABLE ROW LEVEL SECURITY;

