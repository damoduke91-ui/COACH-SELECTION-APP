CREATE OR REPLACE FUNCTION public.reject_locked_season_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  target_environment text;
  target_season_year integer;
  target_status text;
BEGIN
  target_environment := COALESCE(NEW.environment, OLD.environment);
  target_season_year := COALESCE(NEW.season_year, OLD.season_year);

  SELECT status
  INTO target_status
  FROM public.competition_seasons
  WHERE environment = target_environment
    AND season_year = target_season_year;

  IF target_status IN ('completed', 'archived') THEN
    RAISE EXCEPTION 'Season %/% is locked and cannot be changed.',
      target_environment, target_season_year;
  END IF;

  RETURN COALESCE(NEW, OLD);
END;
$$;

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'super8_match_results',
    'season_fixture',
    'round_submissions',
    'coach_team_selections',
    'finals_results',
    'afl_player_round_stats',
    'afl_matches',
    'afl_round_finalisation',
    'weekly_team_lists'
  ]
  LOOP
    IF to_regclass('public.' || table_name) IS NOT NULL THEN
      EXECUTE format(
        'DROP TRIGGER IF EXISTS reject_locked_season_write ON public.%I',
        table_name
      );
      EXECUTE format(
        'CREATE TRIGGER reject_locked_season_write BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.reject_locked_season_write()',
        table_name
      );
    END IF;
  END LOOP;
END
$$;

CREATE OR REPLACE FUNCTION public.archive_preview_season(
  p_season_year integer,
  p_payload jsonb,
  p_source_row_counts jsonb,
  p_checksum text,
  p_premier_name text,
  p_confirmation text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  archive_id bigint;
  grand_final_complete boolean;
BEGIN
  IF p_confirmation <> format('ARCHIVE PREVIEW %s', p_season_year) THEN
    RAISE EXCEPTION 'Typed Preview archive confirmation did not match.';
  END IF;
  IF p_payload IS NULL OR p_source_row_counts IS NULL THEN
    RAISE EXCEPTION 'Archive payload and source row counts are required.';
  END IF;
  IF length(btrim(COALESCE(p_checksum, ''))) < 32 THEN
    RAISE EXCEPTION 'A complete archive checksum is required.';
  END IF;
  IF btrim(COALESCE(p_premier_name, '')) = '' THEN
    RAISE EXCEPTION 'The Premiers must be confirmed before archiving.';
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM public.finals_results
    WHERE environment = 'preview'
      AND season_year = p_season_year
      AND match_code = 'GF'
      AND coach_1_score IS NOT NULL
      AND coach_2_score IS NOT NULL
      AND completed_at IS NOT NULL
  ) INTO grand_final_complete;

  IF NOT grand_final_complete THEN
    RAISE EXCEPTION 'The Preview Grand Final is not complete.';
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtext('archive_preview_season'),
    p_season_year
  );

  INSERT INTO public.season_archives (
    environment, season_year, payload, source_row_counts, checksum, created_by
  ) VALUES (
    'preview', p_season_year, p_payload, p_source_row_counts, p_checksum, auth.uid()
  )
  RETURNING id INTO archive_id;

  UPDATE public.competition_seasons
  SET status = 'archived',
      premier_name = p_premier_name,
      completed_at = COALESCE(completed_at, now()),
      archived_at = now(),
      locked_at = now(),
      updated_at = now()
  WHERE environment = 'preview'
    AND season_year = p_season_year
    AND status = 'active';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'The requested Preview season is not active or does not exist.';
  END IF;

  RETURN archive_id;
END;
$$;

REVOKE ALL ON FUNCTION public.archive_preview_season(integer, jsonb, jsonb, text, text, text)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.archive_preview_season(integer, jsonb, jsonb, text, text, text)
TO service_role;
